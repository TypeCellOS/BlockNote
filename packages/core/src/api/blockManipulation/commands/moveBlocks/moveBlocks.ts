/**
 * Dissolves `placement: "containerOnly"` blocks into their children.
 *
 * A `containerOnly` block (a `column`, say) is defined only in terms of the
 * container that holds it, so it can't land anywhere a regular block goes —
 * moving one out of its container moves its children instead. Every other
 * block passes through as itself.
 */
function dissolveContainerOnlyBlocks(
  blocks: Block<any, any, any>[],
  pmSchema: Schema,
): Block<any, any, any>[] {
  return blocks.flatMap((block) => {
    const nodeType = pmSchema.nodes[block.type];
    // A container denied the `blockGroupChild` group is one declared
    // `placement: "containerOnly"`.
    const isContainerOnly =
      isContainerNode(nodeType) && !isBlockGroupInsertable(nodeType);

    return isContainerOnly
      ? dissolveContainerOnlyBlocks(block.children, pmSchema)
      : [block];
  });
}

type BlockSelectionData = (
  | {
      type: "text";
      headBlockId: string;
      anchorOffset: number;
      headOffset: number;
    }
  | {
      type: "node";
    }
  | {
      type: "cell";
      anchorCellOffset: number;
      headCellOffset: number;
    }
) & {
  anchorBlockId: string;
};

/**
 * `getBlockSelectionData` and `updateBlockSelectionFromData` are used to save
 * and restore the selection within a block, when the block is moved. This is
 * done by first saving the offsets of the anchor and head from the before
 * positions of their surrounding blocks, as well as the IDs of those blocks. We
 * can then recreate the selection by finding the blocks with those IDs, getting
 * their before positions, and adding the offsets to those positions.
 * @param editor The BlockNote editor instance to get the selection data from.
 */
function getBlockSelectionData(
  editor: BlockNoteEditor<any, any, any>,
): BlockSelectionData {
  return editor.transact((tr) => {
    const anchorBlockPosInfo = getBlockInfoNearPos(tr, tr.selection.anchor);

    const anchorBlockId = getNodeId(anchorBlockPosInfo.block.node, tr.doc);

    if (tr.selection instanceof CellSelection) {
      return {
        type: "cell" as const,
        anchorBlockId,
        anchorCellOffset:
          tr.selection.$anchorCell.pos - anchorBlockPosInfo.block.beforePos,
        headCellOffset:
          tr.selection.$headCell.pos - anchorBlockPosInfo.block.beforePos,
      };
    } else if (tr.selection instanceof NodeSelection) {
      return {
        type: "node" as const,
        anchorBlockId,
      };
    } else {
      const headBlockPosInfo = getBlockInfoNearPos(tr, tr.selection.head);

      return {
        type: "text" as const,
        anchorBlockId,
        headBlockId: getNodeId(headBlockPosInfo.block.node, tr.doc),
        anchorOffset: tr.selection.anchor - anchorBlockPosInfo.block.beforePos,
        headOffset: tr.selection.head - headBlockPosInfo.block.beforePos,
      };
    }
  });
}

/**
 * `getBlockSelectionData` and `updateBlockSelectionFromData` are used to save
 * and restore the selection within a block, when the block is moved. This is
 * done by first saving the offsets of the anchor and head from the before
 * positions of their surrounding blocks, as well as the IDs of those blocks. We
 * can then recreate the selection by finding the blocks with those IDs, getting
 * their before positions, and adding the offsets to those positions.
 * @param tr The transaction to update the selection in.
 * @param data The selection data to update the selection with (generated by
 * `getBlockSelectionData`).
 */
function updateBlockSelectionFromData(
  tr: Transaction,
  data: BlockSelectionData,
) {
  const anchorBlockPos = getNodeById(data.anchorBlockId, tr.doc)?.posBeforeNode;
  if (anchorBlockPos === undefined) {
    throw new Error(
      `Could not find block with ID ${data.anchorBlockId} to update selection`,
    );
  }

  let selection: Selection;
  if (data.type === "cell") {
    selection = CellSelection.create(
      tr.doc,
      anchorBlockPos + data.anchorCellOffset,
      anchorBlockPos + data.headCellOffset,
    );
  } else if (data.type === "node") {
    selection = NodeSelection.create(tr.doc, anchorBlockPos + 1);
  } else {
    const headBlockPos = getNodeById(data.headBlockId, tr.doc)?.posBeforeNode;
    if (headBlockPos === undefined) {
      throw new Error(
        `Could not find block with ID ${data.headBlockId} to update selection`,
      );
    }

    selection = TextSelection.create(
      tr.doc,
      anchorBlockPos + data.anchorOffset,
      headBlockPos + data.headOffset,
    );
  }

  tr.setSelection(selection);
}

/**
 * Removes the given blocks from the editor, then inserts them before/after a
 * reference block.
 * @param editor The BlockNote editor instance to move the blocks in.
 * @param blocks The blocks to move.
 * @param referenceBlock The reference block to insert the blocks before/after.
 * @param placement Whether to insert the blocks before or after the reference
 * block.
 */
export function moveBlocks(
  editor: BlockNoteEditor<any, any, any>,
  blocks: Block<any, any, any>[],
  referenceBlock: BlockIdentifier,
  placement: "before" | "after",
) {
  editor.transact((tr) => {
    // Don't fix columns/columnLists in the removal step. Since a move is a
    // rearrangement rather than a deletion, columns that it empties out are
    // deliberately left as-is instead of being collapsed - this keeps moves
    // free of side effects (and reversible by moving back), and matches
    // dragging a block out of a column, which doesn't collapse it either.
    // Fixing them mid-move also broke the following case:
    // <column>
    //  <paragraph></paragraph>
    //  <paragraph>Paragraph</paragraph>
    // </column>
    // When the non-empty block is moved up, the column is seen as empty and
    // collapsed in the removal step, so the following insertion fails.
    removeAndInsertBlocks(tr, blocks, [], { fixContainers: false });
    insertBlocks<any, any, any>(
      tr,
      dissolveContainerOnlyBlocks(blocks, editor.pmSchema),
      referenceBlock,
      placement,
    );
  });
}

/**
 * Removes the selected blocks from the editor, then inserts them before/after a
 * reference block. Also updates the selection to match the original selection
 * using `getBlockSelectionData` and `updateBlockSelectionFromData`.
 * @param editor The BlockNote editor instance to move the blocks in.
 * @param referenceBlock The reference block to insert the selected blocks
 * before/after.
 * @param placement Whether to insert the selected blocks before or after the
 * reference block.
 */
export function moveSelectedBlocksAndSelection(
  editor: BlockNoteEditor<any, any, any>,
  referenceBlock: BlockIdentifier,
  placement: "before" | "after",
) {
  // We want this to be a single step in the undo history
  editor.transact((tr) => {
    const blocks = editor.getSelection()?.blocks || [
      editor.getTextCursorPosition().block,
    ];
    const selectionData = getBlockSelectionData(editor);

    moveBlocks(editor, blocks, referenceBlock, placement);

    updateBlockSelectionFromData(tr, selectionData);
  });
}

// Checks if a regular block would be in a valid place after being moved
// before/after `referenceBlock`. A regular block nests under any non-container
// block (it goes into that block's `blockGroup`), but a container block (e.g. a
// `columnList`) only accepts what its content expression allows.
//
// Deferred to `getInsertionPos` so that "can a block go here?" has exactly
// one answer, shared with `insertBlocks`, and comes from the schema rather
// than from a rule restated here.
function checkPlacementIsValid(
  editor: BlockNoteEditor<any, any, any>,
  referenceBlock: Block<any, any, any>,
  placement: "before" | "after",
  movedBlock: Block<any, any, any>,
): boolean {
  // The PM node type to validate the destination against: the first block
  // `moveBlocks` would actually insert, which is `movedBlock` itself unless it
  // dissolves. A container (e.g. a `callout`) is inserted as its own node
  // type; anything else goes in as a generic `blockContainer` wrapper.
  const first = dissolveContainerOnlyBlocks([movedBlock], editor.pmSchema)[0];
  const firstType = first ? editor.pmSchema.nodes[first.type] : undefined;
  const nodeType =
    firstType && isContainerNode(firstType)
      ? firstType
      : editor.pmSchema.nodes["blockContainer"];

  return editor.transact((tr) => {
    const posInfo = getNodeById(referenceBlock.id, tr.doc);
    if (!posInfo) {
      return false;
    }
    return getInsertionPos(tr.doc, posInfo, placement, nodeType) !== null;
  });
}

// Gets the placement for moving a block up. This has 3 cases:
// 1. If the block has a previous sibling without children, the placement is
// before it.
// 2. If the block has a previous sibling with children, the placement is after
// the last child.
// 3. If the block has no previous sibling, but is nested, the placement is
// before its parent.
// If the placement is invalid, the function is called recursively until a valid
// placement is found. Returns undefined if no valid placement is found, meaning
// the block is already at the top of the document.
function getMoveUpPlacement(
  editor: BlockNoteEditor<any, any, any>,
  movedBlock: Block<any, any, any>,
  prevBlock?: Block<any, any, any>,
  parentBlock?: Block<any, any, any>,
):
  | { referenceBlock: BlockIdentifier; placement: "before" | "after" }
  | undefined {
  let referenceBlock: Block<any, any, any> | undefined;
  let placement: "before" | "after" | undefined;

  if (!prevBlock) {
    if (parentBlock) {
      referenceBlock = parentBlock;
      placement = "before";
    }
  } else if (prevBlock.children.length > 0) {
    referenceBlock = prevBlock.children[prevBlock.children.length - 1];
    placement = "after";
  } else {
    referenceBlock = prevBlock;
    placement = "before";
  }

  // Case when the block is already at the top of the document.
  if (!referenceBlock || !placement) {
    return undefined;
  }

  if (!checkPlacementIsValid(editor, referenceBlock, placement, movedBlock)) {
    const referenceBlockParent = editor.getParentBlock(referenceBlock);
    return getMoveUpPlacement(
      editor,
      movedBlock,
      placement === "after"
        ? referenceBlock
        : editor.getPrevBlock(referenceBlock),
      referenceBlockParent,
    );
  }

  return { referenceBlock, placement };
}

// Gets the placement for moving a block down. This has 3 cases:
// 1. If the block has a next sibling without children, the placement is  after
// it.
// 2. If the block has a next sibling with children, the placement is before the
// first child.
// 3. If the block has no next sibling, but is nested, the placement is
// after its parent.
// If the placement is invalid, the function is called recursively until a valid
// placement is found. Returns undefined if no valid placement is found, meaning
// the block is already at the bottom of the document.
function getMoveDownPlacement(
  editor: BlockNoteEditor<any, any, any>,
  movedBlock: Block<any, any, any>,
  nextBlock?: Block<any, any, any>,
  parentBlock?: Block<any, any, any>,
):
  | { referenceBlock: BlockIdentifier; placement: "before" | "after" }
  | undefined {
  let referenceBlock: Block<any, any, any> | undefined;
  let placement: "before" | "after" | undefined;

  if (!nextBlock) {
    if (parentBlock) {
      referenceBlock = parentBlock;
      placement = "after";
    }
  } else if (nextBlock.children.length > 0) {
    referenceBlock = nextBlock.children[0];
    placement = "before";
  } else {
    referenceBlock = nextBlock;
    placement = "after";
  }

  // Case when the block is already at the bottom of the document.
  if (!referenceBlock || !placement) {
    return undefined;
  }

  if (!checkPlacementIsValid(editor, referenceBlock, placement, movedBlock)) {
    const referenceBlockParent = editor.getParentBlock(referenceBlock);
    return getMoveDownPlacement(
      editor,
      movedBlock,
      placement === "before"
        ? referenceBlock
        : editor.getNextBlock(referenceBlock),
      referenceBlockParent,
    );
  }

  return { referenceBlock, placement };
}

export function moveBlocksUp(
  editor: BlockNoteEditor<any, any, any>,
  blockIdentifier?: BlockIdentifier,
) {
  editor.transact(() => {
    let sourceBlock: Block<any, any, any> | undefined;
    if (blockIdentifier) {
      sourceBlock = editor.getBlock(blockIdentifier);
      if (!sourceBlock) {
        return;
      }
    } else {
      const selection = editor.getSelection();
      sourceBlock =
        selection?.blocks[0] || editor.getTextCursorPosition().block;
    }

    const moveUpPlacement = getMoveUpPlacement(
      editor,
      sourceBlock,
      editor.getPrevBlock(sourceBlock),
      editor.getParentBlock(sourceBlock),
    );

    if (!moveUpPlacement) {
      return;
    }

    if (blockIdentifier) {
      moveBlocks(
        editor,
        [sourceBlock],
        moveUpPlacement.referenceBlock,
        moveUpPlacement.placement,
      );
    } else {
      moveSelectedBlocksAndSelection(
        editor,
        moveUpPlacement.referenceBlock,
        moveUpPlacement.placement,
      );
    }
  });
}

export function moveBlocksDown(
  editor: BlockNoteEditor<any, any, any>,
  blockIdentifier?: BlockIdentifier,
) {
  editor.transact(() => {
    let sourceBlock: Block<any, any, any> | undefined;
    // The block whose position anchors the move (the last of a selection when
    // moving down) vs. the first block that gets inserted, which is what the
    // placement check must validate against.
    let firstMovedBlock: Block<any, any, any> | undefined;
    if (blockIdentifier) {
      sourceBlock = editor.getBlock(blockIdentifier);
      if (!sourceBlock) {
        return;
      }
      firstMovedBlock = sourceBlock;
    } else {
      const selection = editor.getSelection();
      sourceBlock =
        selection?.blocks[selection?.blocks.length - 1] ||
        editor.getTextCursorPosition().block;
      firstMovedBlock =
        selection?.blocks[0] || editor.getTextCursorPosition().block;
    }

    const moveDownPlacement = getMoveDownPlacement(
      editor,
      firstMovedBlock,
      editor.getNextBlock(sourceBlock),
      editor.getParentBlock(sourceBlock),
    );

    if (!moveDownPlacement) {
      return;
    }

    if (blockIdentifier) {
      moveBlocks(
        editor,
        [sourceBlock],
        moveDownPlacement.referenceBlock,
        moveDownPlacement.placement,
      );
    } else {
      moveSelectedBlocksAndSelection(
        editor,
        moveDownPlacement.referenceBlock,
        moveDownPlacement.placement,
      );
    }
  });
}
